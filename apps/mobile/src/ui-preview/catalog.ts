export function activeTab(id: string): number {
  const b = Number(id.split("-")[0]);
  return [6, 7, 8, 21].includes(b)
    ? 0
    : b >= 10 && b <= 12
      ? 1
      : b === 13 || b === 14
        ? 4
        : b >= 15 && b <= 17
          ? 3
          : 2;
}
